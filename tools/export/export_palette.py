"""Export the game's live colour set into src/palette.ts.

    python3 tools/export/export_palette.py --game-repo ../Cosmic-Shore            # write src/palette.ts
    python3 tools/export/export_palette.py --game-repo ../Cosmic-Shore --check    # exit 1 if it would change
    python3 tools/export/export_palette.py --game-repo ../Cosmic-Shore --set photic   # a catalog set instead

"Live" means the colour set the game actually paints with: the one
Assets/_SO_Assets/ThemeManagerDataContainer.asset names in its ColorSet field (Docs/PALETTE.md in the
game repo). Since 2026-11-03 that is Nocturne; before it was the set now called Photic. Reading the
field, not a file name, is what keeps this honest the next time the default changes.

--set <id> picks an entry of the game's ColorSetCatalog.asset (nocturne, photic, dartfrog, ...) instead,
for trying another look. Plain Python 3, no dependencies. Never edit src/palette.ts by hand.
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "src", "palette.ts"))

THEME = "Assets/_SO_Assets/ThemeManagerDataContainer.asset"
CATALOG = "Assets/_SO_Assets/Color Palettes/ColorSetCatalog.asset"

# screensaver order (index = domain id in garland.bin): Jade, Ruby, Blue, Gold
DOMAINS = ["Jade", "Ruby", "Blue", "Gold"]
# screensaver field -> SO_ColorSet field
FIELDS = [
    ("inside", "InsideBlockColor", "InsideBlockColor (rim, HDR, > 1 blooms)"),
    ("outside", "OutsideBlockColor", "OutsideBlockColor (base face)"),
    ("superInside", "SuperShieldedInsideBlockColor", ""),
    ("superOutside", "SuperShieldedOutsideBlockColor", ""),
    ("ship1", "ShipColor1", "ShipColor1 (hull body)"),
    ("ship2", "ShipColor2", "ShipColor2 (domain trim)"),
    ("trail", "TrailHighlightColor", "TrailHighlightColor"),
]

COLOR_RE = re.compile(r"^\s+(\w+): \{r: ([-\d.eE]+), g: ([-\d.eE]+), b: ([-\d.eE]+), a: ([-\d.eE]+)\}")
GUID_RE = re.compile(r"guid: ([0-9a-f]{32})")


def find_by_guid(repo, guid):
    out = subprocess.run(["git", "-C", repo, "grep", "-l", f"guid: {guid}", "--", "*.asset.meta"],
                         capture_output=True, text=True).stdout.split("\n")
    metas = [m for m in out if m.endswith(".asset.meta")]
    if len(metas) != 1:
        sys.exit(f"export_palette: expected one asset with guid {guid}, found {metas}")
    return metas[0][: -len(".meta")]


def live_guid(repo, set_id):
    if set_id is None:
        for line in open(os.path.join(repo, THEME), encoding="utf-8"):
            if line.strip().startswith("ColorSet:"):
                return GUID_RE.search(line).group(1)
        sys.exit(f"export_palette: no ColorSet field in {THEME}")
    lines = open(os.path.join(repo, CATALOG), encoding="utf-8").read().split("\n")
    for i, line in enumerate(lines):
        if line.strip() == f"- id: {set_id}":
            return GUID_RE.search(lines[i + 1]).group(1)
    sys.exit(f"export_palette: no catalog entry '{set_id}' in {CATALOG}")


def read_set(path):
    domains, current = {}, None
    # Unity folds long flow mappings onto a second line ("{r: 0.03, g: 0.2, b: 0.36,\n      a: 1}")
    lines, buf = [], ""
    for raw in open(path, encoding="utf-8").read().replace("\r\n", "\n").split("\n"):
        buf = f"{buf} {raw.strip()}" if buf else raw
        if buf.count("{") == buf.count("}"):
            lines.append(buf)
            buf = ""
    for line in lines:
        m = re.match(r"^  (\w+)Colors:\s*$", line)
        if m:
            current = m.group(1) if m.group(1) in DOMAINS else None
            if current:
                domains[current] = {}
            continue
        m = COLOR_RE.match(line)
        if m and current:
            domains[current][m.group(1)] = tuple(float(v) for v in m.group(2, 3, 4))
    missing = [d for d in DOMAINS if d not in domains]
    if missing:
        sys.exit(f"export_palette: {path} has no {missing}")
    return domains


def num(v):
    s = repr(round(v, 7))
    return s[:-2] if s.endswith(".0") else s


def render(repo, asset, guid, domains, commit):
    name = os.path.splitext(os.path.basename(asset))[0]
    out = [
        "import * as THREE from 'three';",
        "",
        "// GENERATED by tools/export/export_palette.py. Do not edit; re-run the exporter.",
        f"// Source: game repo {asset} (guid {guid}) at {commit[:8]}.",
        "",
        "/**",
        " * The game's domain colours (linear HDR values, as Unity stores them).",
        " * Index order matches the export's domain table: Jade, Ruby, Blue, Gold.",
        " */",
        "export interface DomainColors {",
    ]
    for key, field, note in FIELDS:
        out.append(f"  {key}: THREE.Color;" + (f"  // {note}" if note else ""))
    out += [
        "}",
        "",
        "export const PALETTE_SOURCE = {",
        f"  colorSet: '{name}',",
        f"  guid: '{guid}',",
        f"  gameCommit: '{commit}',",
        "};",
        "",
        "const c = (r: number, g: number, b: number) => new THREE.Color(r, g, b);",
        "",
        "export const DOMAINS: DomainColors[] = [",
    ]
    for d in DOMAINS:
        out.append(f"  {{ // {d}")
        for key, field, _ in FIELDS:
            r, g, b = domains[d][field]
            out.append(f"    {key}: c({num(r)}, {num(g)}, {num(b)}),")
        out.append("  },")
    out += ["];", "", "export const JADE = 0;", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--game-repo", required=True)
    ap.add_argument("--set", help="a ColorSetCatalog id instead of the live set")
    ap.add_argument("--check", action="store_true", help="exit 1 if src/palette.ts would change")
    a = ap.parse_args()
    repo = os.path.abspath(a.game_repo)
    commit = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True,
                            text=True, check=True).stdout.strip()
    guid = live_guid(repo, a.set)
    asset = find_by_guid(repo, guid)
    text = render(repo, asset, guid, read_set(os.path.join(repo, asset)), commit)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    # the commit line moves with every game commit; only the colours and the source set count as drift
    strip = lambda s: "\n".join(l for l in s.split("\n")
                                 if "gameCommit" not in l and not l.startswith("// Source:"))
    same_colours = strip(old) == strip(text)
    if a.check:
        if same_colours:
            print(f"palette: in sync with {os.path.basename(asset)}")
            return 0
        print(f"palette: DRIFT. The {'chosen' if a.set else 'live'} set is {os.path.basename(asset)}; src/palette.ts differs. "
              f"Re-run without --check.")
        return 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"palette: wrote src/palette.ts from {asset} ({'unchanged colours' if same_colours else 'colours changed'})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
